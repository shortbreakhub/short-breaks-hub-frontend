import {createServer} from "vite";
import sharp from "sharp";
import {mkdir, readFile, writeFile} from "node:fs/promises";
import {createHash} from "node:crypto";
import {HOMEPAGE_SELECTION} from "../src/config/homepageSelection.js";

// Explicit editorial refresh, not a runtime request or backend mutation.
// Snapshots make real EN/FR stories available in both dev and prerendered HTML.
const vite = await createServer({mode: "production", appType: "custom", logLevel: "error",
    optimizeDeps: {noDiscovery: true, include: []}, ssr: {resolve: {externalConditions: ["node", "module-sync"]}},
    server: {middlewareMode: true, hmr: false, ws: false}});
try {
    const {getItineraryBySlug} = await vite.ssrLoadModule("/src/api.js");
    const entries = [];
    const imports = [], images = [];
    await mkdir("src/assets/homepage", {recursive: true});
    for (const {key, slug} of HOMEPAGE_SELECTION) {
        const english = await getItineraryBySlug(slug, "en");
        const french = await getItineraryBySlug(slug, "fr");
        if (english.slug !== slug || french.slug !== slug || !english.title || !french.title) throw Error(`Invalid editorial detail: ${slug}`);
        const source = english.hero.replace(/^\//, "");
        if (!/^src\/assets\/itineraries\/[a-z-]+\/[a-z0-9-]+\.jpg$/.test(source)) throw Error(`Unexpected hero source for ${slug}`);
        const original = await readFile(source);
        const metadata = await sharp(original).metadata();
        const variants = [];
        for (const width of key === "shanghai" ? [480, 960, 1440] : [480, 960]) {
            const file = `${key}-${width}.webp`;
            const {data, info} = await sharp(original).rotate().resize({width, withoutEnlargement: true})
                .webp({quality: 80, effort: 6}).toBuffer({resolveWithObject: true});
            await writeFile(`src/assets/homepage/${file}`, data);
            variants.push({file, width: info.width, height: info.height, bytes: data.length});
            imports.push(`import image${imports.length} from "../assets/homepage/${file}";`);
        }
        const offset = imports.length - variants.length;
        images.push(`    ${key}: {src: image${imports.length - 1}, srcSet: ${variants.map((v, i) => `image${offset+i} + " ${v.width}w"`).join(' + ", " + ')}},`);
        entries.push({key, slug, city: english.city, country: english.country, days: english.days,
            copy: Object.fromEntries([["en", english], ["fr", french]].map(([language, detail]) =>
                [language, {title: detail.title, summary: detail.summary}])),
            source, sourceBytes: original.length, sourceSha256: createHash("sha256").update(original).digest("hex"),
            width: metadata.width, height: metadata.height, variants});
    }
    await writeFile("src/content/homepage.json", JSON.stringify(entries, null, 2)+"\n");
    await writeFile("src/utils/homepageImages.js", "// Generated by scripts/sync-homepage-content.mjs; originals and delivery provenance in content/homepage.json.\n"+imports.join("\n")+"\nexport const homepageImages = {\n"+images.join("\n")+"\n};\n");
    console.log(`Refreshed ${entries.length} real English/French stories and ${imports.length} bounded photo derivatives.`);
} finally {await vite.close();}
